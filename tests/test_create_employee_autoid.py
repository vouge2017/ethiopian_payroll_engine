@pytest.fixture
def owner_session(app):
    with app.app_context():
        co = Company(name='SingleCo')
        db.session.add(co)
        db.session.flush()

        owner = User(phone='0911111111', company_id=co.id, role='owner')
        owner.set_password('Test1234!')
        db.session.add(owner)
