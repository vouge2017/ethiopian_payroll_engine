"""Single employee create parity: POST /api/v1/employees must treat a missing
employee_id the way the Quick Start wizard and the bulk import do — generate
the next free EMP### skipping every ID ever used, including soft-deleted rows
— and its duplicate check must span soft-deleted rows too (uq_employee_
company_empid spans them, so reusing a deleted employee's ID is a 409, not an
IntegrityError 500).
"""

